/**
 * Generate lib/kg-data.ts from the cloned PCBSchemaGen_v2 knowledge-graph JSONs.
 *
 * Phase 2 of the PCBSchemaGen port (arXiv:2602.00510): per-IC datasheet-derived
 * pin roles + constraint predicates. This script merges the repo's three KG
 * files (kg.json — 22 curated entries; kg_component.json — 48; and
 * kg/kg_open_schematics.json — 241 covering ~168 real ICs), normalizes them to
 * Sirkit's shape, and emits a checked-in TypeScript data module so the runtime
 * has no dependency on the cloned repo.
 *
 * Provenance: PCBSchemaGen_v2 (MIT, https://github.com/HZou9/PCBSchemaGen_v2).
 * Re-run after pulling KG updates:  npx tsx scripts/build-kg.ts
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const REPO = join(process.cwd(), "PCBSchemaGen_v2");
const OUT = join(process.cwd(), "lib", "kg-data.ts");

type RawConstraint = Record<string, unknown> & { type?: string };
type RawEntry = {
  id?: string;
  category?: string;
  note?: string;
  pin_roles?: Record<string, string>;
  generic_constraints?: RawConstraint[];
};

type KgConstraint =
  | { type: "supply_pair"; vddPin: string; gndPin: string }
  | { type: "must_be_connected"; pins: string[] }
  | { type: "driving_pair"; gatePin: string; sourcePin: string }
  | { type: "differential_distinct"; pins: string[] };

type KgEntry = {
  note: string;
  pinRoles: Record<string, string>;
  constraints: KgConstraint[];
};

function normalizeConstraint(raw: RawConstraint): KgConstraint | null {
  switch (raw.type) {
    case "supply_pair":
      if (typeof raw.vdd_pin === "string" && typeof raw.gnd_pin === "string") {
        return { type: "supply_pair", vddPin: raw.vdd_pin, gndPin: raw.gnd_pin };
      }
      return null;
    case "must_be_connected":
      if (Array.isArray(raw.pins) && raw.pins.every((p) => typeof p === "string" || typeof p === "number")) {
        return { type: "must_be_connected", pins: (raw.pins as (string | number)[]).map(String) };
      }
      return null;
    case "driving_pair":
      if (raw.gate_pin !== undefined && raw.source_pin !== undefined) {
        return { type: "driving_pair", gatePin: String(raw.gate_pin), sourcePin: String(raw.source_pin) };
      }
      return null;
    case "differential_pair_must_be_distinct":
      if (Array.isArray(raw.pins)) {
        return { type: "differential_distinct", pins: (raw.pins as (string | number)[]).map(String) };
      }
      return null;
    default:
      return null;
  }
}

function collect(file: string, out: Map<string, KgEntry>): void {
  const path = join(REPO, file);
  if (!existsSync(path)) {
    console.warn(`skip (missing): ${file}`);
    return;
  }
  const json = JSON.parse(readFileSync(path, "utf8")) as { components?: Record<string, RawEntry> };
  for (const [key, raw] of Object.entries(json.components ?? {})) {
    // ID lives in the entry for the array-keyed files, in the key for kg.json.
    const id = (raw.id ?? key).trim().toUpperCase();
    // Real ICs and discrete semiconductors carry useful datasheet constraints;
    // generic passives (R/C/L/D) are covered by Sirkit's pin-type ERC already.
    const category = (raw.category ?? "").toLowerCase();
    if (!["ic", "mosfet", "transistor", "diode_ic"].includes(category) || id.length < 4) continue;

    const constraints = (raw.generic_constraints ?? [])
      .map(normalizeConstraint)
      .filter((c): c is KgConstraint => c !== null);
    const pinRoles = raw.pin_roles ?? {};
    if (constraints.length === 0 && Object.keys(pinRoles).length === 0) continue;

    const existing = out.get(id);
    // Prefer the richer entry when the same IC appears in multiple files.
    if (existing && existing.constraints.length >= constraints.length) continue;
    out.set(id, { note: raw.note ?? "", pinRoles, constraints });
  }
}

const entries = new Map<string, KgEntry>();
collect("kg/kg_open_schematics.json", entries);
collect("kg_component.json", entries);
collect("kg.json", entries);

const sorted = [...entries.entries()].sort(([a], [b]) => a.localeCompare(b));
const counts = { supply_pair: 0, must_be_connected: 0, driving_pair: 0, differential_distinct: 0 };
for (const [, e] of sorted) for (const c of e.constraints) counts[c.type]++;

const header = `/**
 * Datasheet-derived per-IC knowledge graph: pin roles + constraint predicates.
 *
 * GENERATED by scripts/build-kg.ts from PCBSchemaGen_v2's KG files — do not edit
 * by hand; re-run the script instead. Source data: PCBSchemaGen
 * (arXiv:2602.00510), MIT — https://github.com/HZou9/PCBSchemaGen_v2
 *
 * ${sorted.length} ICs · ${counts.supply_pair} supply_pair · ${counts.must_be_connected} must_be_connected · ${counts.driving_pair} driving_pair · ${counts.differential_distinct} differential_distinct
 */

import type { KgEntry } from "./kg";

export const KG_DATA: Record<string, KgEntry> = `;

writeFileSync(OUT, header + JSON.stringify(Object.fromEntries(sorted), null, 1) + ";\n");
console.log(`Wrote ${OUT}: ${sorted.length} ICs, constraints = ${JSON.stringify(counts)}`);
