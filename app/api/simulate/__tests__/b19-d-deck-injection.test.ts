/**
 * [B19-D I5e review] The legacy /api/simulate ngspice deck: every caller string that becomes a deck token is screened.
 *
 * The input guard screened a component's value, a net label's name and the analysis fields for line breaks, but the SPICE
 * element name is the component's reference (`refDes`, or its `id` when there is none), and that was never screened. A
 * reference carrying a newline wrote a second, live `.control` block (with `shell`) into the deck handed to ngspice; the output
 * screen deliberately does not look for `.control`, because the serializer writes one itself.
 *
 * ZERO real processes: the child process and the temp files are fakes, as in the B16.0.24 parity suite.
 */
import { afterEach, describe, expect, it, vi } from "vitest";

const spawnState = vi.hoisted(() => ({ calls: 0 }));
vi.mock("node:child_process", async (orig) => {
  const actual = await orig() as Record<string, unknown>;
  const { EventEmitter } = await import("node:events");
  return {
    ...actual,
    spawn: () => {
      spawnState.calls += 1;
      const child = new EventEmitter() as InstanceType<typeof EventEmitter> & { stdout: InstanceType<typeof EventEmitter>; stderr: InstanceType<typeof EventEmitter>; kill: () => void };
      child.stdout = new EventEmitter();
      child.stderr = new EventEmitter();
      child.kill = () => {};
      queueMicrotask(() => child.emit("close", 0));
      return child;
    },
  };
});
const fsState = vi.hoisted(() => ({ decks: [] as string[] }));
vi.mock("node:fs/promises", async (orig) => ({
  ...(await orig() as Record<string, unknown>),
  writeFile: async (_path: string, content: string) => { fsState.decks.push(String(content)); },
  open: async () => { throw Object.assign(new Error("ENOENT"), { code: "ENOENT" }); },
  mkdtemp: async (prefix: string) => `${prefix}fake`,
  rm: async () => {},
}));
const deckOverride = vi.hoisted(() => ({ netlist: null as string | null }));
vi.mock("@/app/lib/netlist", async (orig) => {
  const actual = await orig() as typeof import("@/app/lib/netlist");
  return {
    ...actual,
    schematicToSpice: (...args: Parameters<typeof actual.schematicToSpice>) => {
      const result = actual.schematicToSpice(...args);
      return deckOverride.netlist === null ? result : { ...result, netlist: deckOverride.netlist };
    },
  };
});

import { injectAuthorizedPrincipal, resetInjectedIdentity } from "@/app/lib/auth/test-support";
import { POST as simulatePost } from "../route";

const SEL = { "x-sirkit-tenant-id": "local", "x-sirkit-project-id": "local", "x-sirkit-branch-id": "local" };
const NEWLINE = String.fromCharCode(10);
const INJECTED = ["R1 N001 0 1k", ".control", "shell id", ".endc", "*"].join(NEWLINE);

function simulate(resistor: Record<string, unknown>): Request {
  const state = {
    components: [
      { id: "v1", type: "voltage-source", value: "5", position: { x: 100, y: 100 }, rotation: 0, refDes: "V1" },
      { type: "resistor", value: "1k", position: { x: 130, y: 70 }, rotation: 0, ...resistor },
      { id: "g1", type: "ground", value: "", position: { x: 100, y: 180 }, rotation: 0, refDes: "" },
    ],
    wires: [
      { id: "w1", vertices: [{ x: 100, y: 130 }, { x: 100, y: 160 }] },
      { id: "w2", vertices: [{ x: 160, y: 70 }, { x: 160, y: 160 }, { x: 100, y: 160 }] },
    ],
    netLabels: [],
  };
  injectAuthorizedPrincipal({ userId: "u1", tenantId: "local", projectId: "local", role: "editor" });
  return new Request("http://localhost/api/simulate", { method: "POST", headers: { "content-type": "application/json", origin: "http://localhost", ...SEL }, body: JSON.stringify({ state }) });
}

afterEach(() => { resetInjectedIdentity(); spawnState.calls = 0; fsState.decks = []; deckOverride.netlist = null; });

describe("[B19-D I5e review] a component reference cannot write a directive into the ngspice deck", () => {
  it.each([
    ["a reference with a newline", { id: "r1", refDes: INJECTED }],
    ["an id with a newline and no reference", { id: INJECTED }],
    ["a reference with a carriage return", { id: "r1", refDes: ["R1", ".control"].join(String.fromCharCode(13)) }],
    ["a reference with a NUL", { id: "r1", refDes: ["R1", "x"].join(String.fromCharCode(0)) }],
    ["a reference with a backtick", { id: "r1", refDes: "R1`id`" }],
  ])("%s is refused before any deck is written or process spawned", async (_label, resistor) => {
    const res = await simulatePost(simulate(resistor));
    expect(res.status).toBe(400);
    expect(fsState.decks).toEqual([]);
    expect(spawnState.calls).toBe(0);
  });

  it("a deck with a second control block is refused by the output screen (defence in depth)", async () => {
    deckOverride.netlist = ["* Generated by sirkit", "R1 N001 0 1k", ".tran 1m 10m", ".control", "shell id", ".endc", ".control", "set filetype=ascii", "run", "write result.raw", ".endc", ".end"].join(NEWLINE);
    const res = await simulatePost(simulate({ id: "r1", refDes: "R1" }));
    expect(res.status).toBe(400);
    expect(spawnState.calls).toBe(0);
  });

  it("a normal circuit writes exactly one control block and runs once (baseline)", async () => {
    await simulatePost(simulate({ id: "r1", refDes: "R1" }));
    expect(fsState.decks).toHaveLength(1);
    expect(fsState.decks[0]!.split(NEWLINE).filter((line) => /^\s*\.control\b/i.test(line))).toHaveLength(1);
    expect(spawnState.calls).toBe(1);
  });
});
