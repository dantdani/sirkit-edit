import type {
  SchematicState,
  SchComponent,
  SchComponentType,
} from "@/lib/schematic-types";
import { PIN_NAMES, normalizeRefDes, schDisplayRef } from "@/lib/schematic-types";
import { pinWorldPos, pointKey } from "./geometry";
import { buildNetUnionFind } from "./connectivity";

// ─── Public types ─────────────────────────────────────────────────────────────

export type SpiceAnalysis =
  | { type: "tran"; tstep: string; tstop: string; uic?: boolean }
  | { type: "ac"; sweep: "dec" | "oct" | "lin"; points: number; fstart: string; fstop: string }
  | { type: "dc"; source: string; vstart: string; vstop: string; vstep: string }
  | { type: "op" };

const DEFAULT_ANALYSIS: SpiceAnalysis = { type: "tran", tstep: "10u", tstop: "10m" };

// ─── Value normalization ──────────────────────────────────────────────────────

function normalizeValue(raw: string, type: SchComponentType): string {
  let v = raw.trim();

  // Strip unit symbols
  v = v.replace(/\s*[Ωω]/g, "");
  v = v.replace(/ohms?$/i, "");
  v = v.replace(/F$/i, "");   // 100nF → 100n
  v = v.replace(/H$/i, "");   // 10uH → 10u
  v = v.replace(/µ/g, "u");   // Unicode mu → ASCII u

  if (type === "voltage-source" || type === "current-source") {
    if (/\bac\b/i.test(v)) return "AC 1 SIN(0 1 1k)";
    v = v.replace(/V$/i, "").trim();
  }

  // SPICE milli = m, mega = Meg. User input "M" for resistance = mega.
  // Replace bare uppercase M (not already part of Meg/MEG) with Meg.
  v = v.replace(/M(?![eEgG])/g, "Meg");

  return v || "0";
}

// ─── SPICE element naming ─────────────────────────────────────────────────────

const TYPE_PREFIX: Record<SchComponentType, string> = {
  resistor:         "R",
  capacitor:        "C",
  inductor:         "L",
  diode:            "D",
  "voltage-source": "V",
  "current-source": "I",
  ground:           "G",
};

// B07.1 — SPICE element names are PRESENTATION and derive from the displayed
// reference (`refDes ?? id`), never from the stable id directly. This rule is
// mirrored EXACTLY by the frontend probe-key derivation (frontendSpiceName in
// app/page.tsx) — the two must stay in lockstep or probe vectors stop
// matching emitted element names.
function spiceName(comp: SchComponent): string {
  const prefix = TYPE_PREFIX[comp.type];
  const display = normalizeRefDes(schDisplayRef(comp)).toUpperCase();
  return display.startsWith(prefix) ? display : prefix + display;
}

// ─── Main serializer ──────────────────────────────────────────────────────────

export function schematicToSpice(
  state: SchematicState,
  options?: { analysis?: SpiceAnalysis; rawOutputPath?: string },
): { netlist: string; nodeMap: Record<string, string>; pinNodes: Record<string, string> } {
  const analysis     = options?.analysis ?? DEFAULT_ANALYSIS;
  const rawOutputPath = options?.rawOutputPath;

  if (state.components.length === 0) {
    return { netlist: "* Generated by sirkit\n.end\n", nodeMap: {}, pinNodes: {} };
  }

  // Build the Union-Find over wire vertices, pin sites, and net labels. This
  // unifies co-located pins automatically, and same-name labels act as
  // virtual wires between their anchor points.
  const netLabels = state.netLabels ?? [];
  const uf = buildNetUnionFind(state.components, state.wires, [], netLabels);

  // 2. Ground net: union all ground-component pin sites AND every ground
  //    label site ("ground"-kind, or named GND/0) → root = node 0.
  const gndSites: string[] = state.components
    .filter((c) => c.type === "ground")
    .map((g) => pointKey(pinWorldPos(g, "pin")));
  for (const l of netLabels) {
    const name = l.name.trim().toUpperCase();
    if (l.kind === "ground" || name === "GND" || name === "0") {
      gndSites.push(pointKey(l.position));
    }
  }
  let gndRoot: string | null = null;
  for (const site of gndSites) {
    if (gndRoot === null) {
      gndRoot = uf.find(site);
    } else {
      uf.union(gndRoot, site);
      gndRoot = uf.find(gndRoot);
    }
  }
  const finalGndRoot = gndRoot !== null ? uf.find(gndRoot) : null;

  // 3. Assign node names (deterministic: sort non-ground roots lexicographically)
  const rootSet = new Set<string>();
  for (const comp of state.components) {
    for (const pin of PIN_NAMES[comp.type] ?? []) {
      rootSet.add(uf.find(pointKey(pinWorldPos(comp, pin))));
    }
  }

  const nodeNames = new Map<string, string>();
  if (finalGndRoot !== null) nodeNames.set(finalGndRoot, "0");

  let counter = 1;
  for (const root of [...rootSet].filter((r) => r !== finalGndRoot).sort()) {
    nodeNames.set(root, `N${String(counter++).padStart(3, "0")}`);
  }

  function nodeForPin(comp: SchComponent, pin: string): string {
    const root = uf.find(pointKey(pinWorldPos(comp, pin)));
    return nodeNames.get(root) ?? "N???";
  }

  // Pin position → node name (used by frontend for wire/pin probing).
  // Also includes every wire vertex so that clicking anywhere along a wire's
  // visible extent resolves to the net via point-coordinate lookup.
  const pinNodes: Record<string, string> = {};
  for (const comp of state.components) {
    for (const pin of PIN_NAMES[comp.type] ?? []) {
      const pos = pointKey(pinWorldPos(comp, pin));
      const root = uf.find(pos);
      pinNodes[pos] = nodeNames.get(root) ?? "N???";
    }
  }
  for (const wire of state.wires) {
    for (const v of wire.vertices) {
      const pos = pointKey(v);
      if (pos in pinNodes) continue;
      const root = uf.find(pos);
      const name = nodeNames.get(root);
      if (name) pinNodes[pos] = name;
    }
  }

  // 4. Emit SPICE lines
  const lines: string[] = ["* Generated by sirkit", ""];

  let hasDiode = false;
  const seenNames = new Set<string>();

  function uniqueName(base: string): string {
    let name = base, n = 1;
    while (seenNames.has(name)) name = `${base}_${++n}`;
    seenNames.add(name);
    return name;
  }

  const voltageSrcs  = state.components.filter((c) => c.type === "voltage-source");
  const currentSrcs  = state.components.filter((c) => c.type === "current-source");
  const passives     = state.components
    .filter((c) => !["voltage-source", "current-source", "ground"].includes(c.type))
    .sort((a, b) => a.id.localeCompare(b.id));

  for (const comp of [...voltageSrcs, ...currentSrcs, ...passives]) {
    const name = uniqueName(spiceName(comp));
    const val  = normalizeValue(comp.value, comp.type);

    switch (comp.type) {
      case "voltage-source": {
        const np = nodeForPin(comp, "+"), nm = nodeForPin(comp, "-");
        // Always emit an AC magnitude so .ac analyses produce non-zero output.
        // Harmless for .tran/.dc/.op.
        if (val.startsWith("AC")) {
          lines.push(`${name} ${np} ${nm} ${val}`);
        } else {
          lines.push(`${name} ${np} ${nm} DC ${val} AC 1`);
        }
        break;
      }
      case "current-source": {
        const np = nodeForPin(comp, "+"), nm = nodeForPin(comp, "-");
        lines.push(`${name} ${np} ${nm} DC ${val}`);
        break;
      }
      case "resistor":
        lines.push(`${name} ${nodeForPin(comp, "left")} ${nodeForPin(comp, "right")} ${val}`);
        break;
      case "capacitor":
        lines.push(`${name} ${nodeForPin(comp, "left")} ${nodeForPin(comp, "right")} ${val}`);
        break;
      case "inductor":
        lines.push(`${name} ${nodeForPin(comp, "left")} ${nodeForPin(comp, "right")} ${val}`);
        break;
      case "diode":
        lines.push(`${name} ${nodeForPin(comp, "anode")} ${nodeForPin(comp, "cathode")} D1N4148`);
        hasDiode = true;
        break;
    }
  }

  // 5. Model lines, analysis directive, control block
  lines.push("");
  if (hasDiode) lines.push(".model D1N4148 D(IS=2.52e-9 N=1.752)");

  switch (analysis.type) {
    case "tran":
      lines.push(`.tran ${analysis.tstep} ${analysis.tstop}${analysis.uic ? " uic" : ""}`);
      break;
    case "ac":
      lines.push(`.ac ${analysis.sweep} ${analysis.points} ${analysis.fstart} ${analysis.fstop}`);
      break;
    case "dc":
      lines.push(`.dc ${analysis.source} ${analysis.vstart} ${analysis.vstop} ${analysis.vstep}`);
      break;
    case "op":
      lines.push(".op");
      break;
  }

  lines.push(
    ".control",
    "set filetype=ascii",
    "run",
    rawOutputPath ? `write ${rawOutputPath}` : "write",
    ".endc",
    ".end",
  );

  return {
    netlist:  lines.join("\n"),
    nodeMap:  Object.fromEntries(nodeNames.entries()),
    pinNodes,
  };
}
